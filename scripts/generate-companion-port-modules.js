#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { COMPANION_PORT_CATALOGUE } = require('./companion-port-catalogue');

const ROOT = path.join(__dirname, '..');
// Only the extension-side module is generated here. The matching Python
// module is generated in SysAdminDoc/AstraDownloader from its own copy of
// companion-port-catalogue.json - the two copies of the JSON are the
// contract, and changing the ports is a two-repository change.
const JS_PATH = path.join(ROOT, 'extension', 'core', 'companion-ports.js');

function renderJavascript(catalogue) {
    return `// Generated from scripts/companion-port-catalogue.json. Do not edit this file directly.\n(() => {\n    'use strict';\n\n    const core = globalThis.YTKitCore || (globalThis.YTKitCore = {});\n    if (core.companionPorts) return;\n\n    const companionPorts = Object.freeze({\n        schemaVersion: 1,\n        host: ${JSON.stringify(catalogue.host)},\n        origin: ${JSON.stringify(catalogue.origin)},\n        primaryPort: ${catalogue.primaryPort},\n        ports: Object.freeze(${JSON.stringify(catalogue.ports)}),\n        hostPermissions: Object.freeze(${JSON.stringify(catalogue.hostPermissions)}),\n        cspOrigins: Object.freeze(${JSON.stringify(catalogue.cspOrigins)})\n    });\n    core.companionPorts = companionPorts;\n\n    if (typeof module !== 'undefined' && module.exports) {\n        module.exports = companionPorts;\n    }\n})();\n`;
}

fs.writeFileSync(JS_PATH, renderJavascript(COMPANION_PORT_CATALOGUE), 'utf8');
console.log(`[companion-port-catalogue] generated ${path.relative(ROOT, JS_PATH)}`);
