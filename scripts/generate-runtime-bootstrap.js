const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const MANIFEST_PATH = path.join(ROOT, 'extension', 'manifest.json');
const OUTPUT_PATH = path.join(ROOT, 'extension', 'runtime-bootstrap.js');
const LOADER_OUTPUT_PATH = path.join(ROOT, 'extension', 'runtime-core-loader.mjs');
const LOADER_MODULE = 'runtime-core-loader.mjs';

