#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const MANIFEST_PATH = path.join(ROOT, 'extension', 'manifest.json');
const OUTPUT_PATH = path.join(ROOT, 'extension', 'runtime-bootstrap.js');
const LOADER_OUTPUT_PATH = path.join(ROOT, 'extension', 'runtime-core-loader.mjs');
const LOADER_MODULE = 'runtime-core-loader.mjs';

const FEATURE_SETTINGS = Object.freeze({
    'features/subtitles/index.js': ['autoSubtitles', 'autoSubtitlesWhenMuted', 'dualLanguageSubtitles', 'subtitleDownload', 'subtitlesOnRewind'],
    'features/video-filters/index.js': ['videoVisualFilters', 'photosensitiveFlashProtection'],
    'features/blue-light-filter/index.js': ['blueLightFilter'],
    'features/theme-css/index.js': ['colorTheme', 'oledTheme', 'themeAccentColor'],
    'features/home-subs-css/index.js': ['fullWidthSubscriptions', 'hideSubscriptionOptions', 'hideVoiceSearch', 'widenSearchBar'],
    'features/chat-style-comments/index.js': ['chatStyleComments'],
    'features/sticky-video/index.js': ['stickyVideo'],
    'features/sticky-chat/index.js': ['stickyChat'],
    'features/video-hider/index.js': ['hideVideosFromHome', 'hideVideosHideAutoDubbed', 'hideVideosHideLive', 'hideVideosHideMixes', 'hideVideosHideMovies', 'hideVideosHidePlaylists', 'hideVideosHideUpcoming'],
    'features/video-notes/index.js': ['videoNotes'],
    'features/subscription-view/index.js': ['subscriptionViewControls'],
    'features/subscription-groups/index.js': ['subscriptionGroups'],
    'features/digital-wellbeing/index.js': ['digitalWellbeing'],
    'features/youtube-music-compat/index.js': ['musicVideoSpeedLock'],
    'features/search-hygiene/index.js': ['searchHideRelatedSearches', 'searchHideUnrelatedShelves', 'searchHideWatchedRecommended'],
    'features/search-while-watching/index.js': ['searchWhileWatching'],
    'features/video-insights/index.js': ['videoInsights'],
    'features/return-dislike/index.js': ['returnDislike', 'returnDislikeOnCards'],
    'features/sponsorblock/index.js': ['sponsorBlock'],
    'features/dearrow/index.js': ['deArrow', 'deArrowChannelOverridesPanel', 'dearrowPeekButton'],
});

// There is deliberately no route gate here. YouTube is a single-page app: the
// bootstrap runs once, on the landing URL, but the session then navigates
// everywhere. The monolith builds its feature array at load time, so a module
// imported after that point can no longer displace the inline fallback that
// already won — which meant a route-gated module was missing for the WHOLE
// session whenever the landing URL did not match. That is how the in-page
// Subscription Groups copy (with its destructive import) and the fallback
// Video Hider (with no Mark-Watched runtime at all) reached users, selected by
// nothing more than which page they happened to open first.
//
// Modules are still skipped when every feature they provide is switched off
// (FEATURE_SETTINGS above) — that gate keys on user settings, which do not
// change under the session's feet.

function readManifest() {
    return JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
}

function findRuntimeEntry(manifest) {
    const entry = manifest.content_scripts?.find((candidate) => {
        const scripts = candidate['x-ytkit-runtime-modules'] || candidate.js || [];
        return scripts.includes('ytkit.js');
    });
    if (!entry) {
        throw new Error('Could not find the normal YouTube runtime content-script entry');
    }
    return entry;
}

function readRuntimeModules() {
    const manifest = readManifest();
    const entry = findRuntimeEntry(manifest);
    const modules = entry['x-ytkit-runtime-modules'] || entry.js;

    if (!Array.isArray(modules) || modules.length === 0) {
        throw new Error('The normal YouTube runtime module list is empty');
    }
    if (!modules.includes('ytkit.js')) {
        throw new Error('The normal YouTube runtime module list must include ytkit.js');
    }
    if (modules.at(-1) !== 'ytkit.js') {
        throw new Error('ytkit.js must remain the final runtime module so feature factories are ready before construction');
    }
    if (modules.includes('runtime-bootstrap.js')) {
        throw new Error('runtime-bootstrap.js cannot load itself');
    }

    for (const modulePath of modules) {
        if (!modulePath.endsWith('.js')) {
            throw new Error(`Runtime module is not JavaScript: ${modulePath}`);
        }
        if (!fs.existsSync(path.join(ROOT, 'extension', modulePath))) {
            throw new Error(`Runtime module does not exist: ${modulePath}`);
        }
    }

    return modules;
}

function render(modules) {
    const moduleLiteral = JSON.stringify(modules, null, 4)
        .split('\n')
        .map((line) => `    ${line}`)
        .join('\n');
    const settingsLiteral = JSON.stringify(FEATURE_SETTINGS, null, 4)
        .split('\n')
        .map((line) => `    ${line}`)
        .join('\n');

    return `// Generated by scripts/generate-runtime-bootstrap.js. Do not edit by hand.
(() => {
    'use strict';

    const BOOTSTRAP_STATE_KEY = '__ytkitRuntimeBootstrap';
    const priorState = globalThis[BOOTSTRAP_STATE_KEY]
        || (globalThis.__ytkitRuntimePromise ? {
            schemaVersion: 1,
            phase: 'starting',
            active: true,
            duplicateInjections: 0,
            generation: 0,
            startedAt: Date.now(),
            failure: null
        } : null);
    if (priorState && !globalThis[BOOTSTRAP_STATE_KEY]) {
        // A tab may still contain a runtime from the pre-state bootstrap. Make
        // that legacy generation observable before declining re-entry.
        globalThis[BOOTSTRAP_STATE_KEY] = priorState;
    }
    if (priorState && (priorState.phase === 'starting' || priorState.phase === 'ready')) {
        priorState.duplicateInjections = Number(priorState.duplicateInjections || 0) + 1;
        priorState.lastDuplicateAt = Date.now();
        try {
            console.warn('[YTKit] Duplicate runtime bootstrap ignored.', {
                duplicateInjections: priorState.duplicateInjections,
                phase: priorState.phase
            });
        } catch (_) {
            // reason: diagnostics must not block the existing runtime
        }
        return;
    }

    const bootstrapState = {
        schemaVersion: 1,
        phase: 'starting',
        active: true,
        duplicateInjections: 0,
        generation: Number(priorState?.generation || 0) + 1,
        startedAt: Date.now(),
        completedAt: null,
        failure: null
    };
    globalThis[BOOTSTRAP_STATE_KEY] = bootstrapState;

    const RUNTIME_MODULES = Object.freeze(
${moduleLiteral}
    );
    const FEATURE_SETTINGS = Object.freeze(
${settingsLiteral}
    );
    const extensionRuntime = globalThis.chrome?.runtime || globalThis.browser?.runtime;
    const getURL = extensionRuntime?.getURL;

    if (typeof getURL !== 'function') {
        bootstrapState.phase = 'failed';
        bootstrapState.active = false;
        bootstrapState.failure = 'runtime-url-unavailable';
        console.error('[YTKit] Extension runtime URL API is unavailable');
        return;
    }

    const publishZeroAdStatus = () => new Promise((resolve) => {
        if (typeof extensionRuntime?.sendMessage !== 'function') {
            resolve(null);
            return;
        }
        let settled = false;
        const finish = (status) => {
            if (settled) return;
            settled = true;
            const state = status?.ok && status?.enabled ? 'enabled' : 'unavailable';
            try {
                globalThis.document?.documentElement?.setAttribute('data-ytkit-zero-ad-ruleset', state);
            } catch (_) {
                // reason: diagnostics must never delay or fail runtime startup
            }
            bootstrapState.zeroAdRuleset = state;
            resolve(status || null);
        };
        try {
            const pending = extensionRuntime.sendMessage({ type: 'YTKIT_ZERO_AD_STATUS' }, finish);
            if (pending && typeof pending.then === 'function') pending.then(finish, () => finish(null));
        } catch (_) {
            finish(null);
        }
    });

    void publishZeroAdStatus();

    const readRuntimeSettings = () => new Promise((resolve) => {
        const storage = globalThis.chrome?.storage?.local || globalThis.browser?.storage?.local;
        if (typeof storage?.get !== 'function') {
            resolve({});
            return;
        }
        let settled = false;
        const finish = (result) => {
            if (settled) return;
            settled = true;
            const settings = result?.ytSuiteSettings;
            resolve(settings && typeof settings === 'object' ? settings : {});
        };
        try {
            const pending = storage.get('ytSuiteSettings', finish);
            if (pending && typeof pending.then === 'function') pending.then(finish, () => finish({}));
        } catch (_) {
            try {
                const pending = storage.get('ytSuiteSettings');
                if (pending && typeof pending.then === 'function') pending.then(finish, () => finish({}));
                else finish({});
            } catch (_) {
                finish({});
            }
        }
    });

    // Only the settings gate remains: a module whose every feature is switched
    // off is skipped. Route gating is deliberately absent — see the note in
    // scripts/generate-runtime-bootstrap.js.
    const shouldLoadFeature = (modulePath, settings) => {
        const keys = FEATURE_SETTINGS[modulePath];
        return !(Array.isArray(keys) && keys.length
            && keys.every((key) => Object.hasOwn(settings, key) && settings[key] === false));
    };

    // Per-stage attribution. loadRuntime is four serial awaits and, until this
    // existed, a startup regression could only be measured end-to-end — which
    // is how a ~2x one accumulated across ~15 commits before anyone could say
    // WHICH stage grew. Cost is four performance.now() reads; the numbers ride
    // on the bootstrap state that already carries startedAt/completedAt, so
    // diagnostics and the startup bench can both read them.
    const stageTimings = Object.create(null);
    bootstrapState.stageTimings = stageTimings;
    const timeStage = async (name, run) => {
        const startedAt = performance.now();
        try {
            return await run();
        } finally {
            stageTimings[name] = Math.round((performance.now() - startedAt) * 100) / 100;
        }
    };

    const loadRuntime = async () => {
        const firstFeatureIndex = RUNTIME_MODULES.findIndex((modulePath) => modulePath.startsWith('features/'));
        const optionalFeatureModules = firstFeatureIndex === -1
            ? []
            : RUNTIME_MODULES.slice(firstFeatureIndex, -1);
        const settingsPromise = readRuntimeSettings();
        await timeStage('coreLoaderMs', () => import(getURL('${LOADER_MODULE}')));
        // The route bridge is installed here, not by the module itself: it is
        // the one foundation module with cross-module dependencies at install
        // time, and self-installing on load both forced the whole graph to load
        // sequentially and failed SILENTLY (the installer returns false, it does
        // not throw) whenever its dependencies had not registered yet. Without
        // it, SPA route tokens never advance and every stale-result guard that
        // compares them stops working.
        const routeBridgeInstalled = globalThis.YTKitCore?.installLifecycleRouteBridge?.() === true;
        if (!routeBridgeInstalled) {
            console.error('[YTKit] Lifecycle route bridge failed to install; SPA route tokens will not advance');
        }
        bootstrapState.routeBridgeInstalled = routeBridgeInstalled;
        const settings = await timeStage('settingsReadMs', () => settingsPromise);
        const deferredFeatureModules = optionalFeatureModules.filter((modulePath) =>
            modulePath !== 'features/download-ui/index.js'
            && shouldLoadFeature(modulePath, settings)
        );
        stageTimings.featureModuleCount = deferredFeatureModules.length;
        await timeStage('featureModulesMs', () => Promise.all(
            deferredFeatureModules.map((modulePath) => import(getURL(modulePath)))
        ));
        // The monolith reads YTKitFeatures while constructing its top-level
        // feature array. It must execute only after every selected peeled
        // module has registered its factory; otherwise the inline fallback
        // silently wins and extension users run a different implementation
        // from userscript tests.
        await timeStage('monolithMs', () => import(getURL('ytkit.js')));
        globalThis.dispatchEvent?.(new CustomEvent('ytkit-runtime-ready'));
    };

    const scheduleRuntime = () => new Promise((resolve, reject) => {
        const run = () => {
            loadRuntime().then(resolve, reject);
        };

        Promise.resolve().then(run);
    });

    globalThis.__ytkitRuntimePromise = scheduleRuntime().then(
        (result) => {
            bootstrapState.phase = 'ready';
            bootstrapState.active = true;
            bootstrapState.completedAt = Date.now();
            return result;
        },
        (error) => {
            bootstrapState.phase = 'failed';
            bootstrapState.active = false;
            bootstrapState.completedAt = Date.now();
            bootstrapState.failure = String(error?.message || error || 'runtime-load-failed').slice(0, 240);
            console.error('[YTKit] Runtime module load failed', error);
            throw error;
        }
    );
})();
`;
}

function renderLoader(modules) {
    const firstFeatureIndex = modules.findIndex((modulePath) => modulePath.startsWith('features/'));
    const foundationModules = firstFeatureIndex === -1
        ? modules.slice(0, -1)
        : modules.slice(0, firstFeatureIndex);
    const criticalFeature = 'features/download-ui/index.js';
    if (!modules.includes(criticalFeature)) {
        throw new Error(`Runtime module catalogue must include ${criticalFeature}`);
    }
    const imports = [...foundationModules, criticalFeature];
    const moduleLiteral = JSON.stringify(imports, null, 4)
        .split('\n')
        .map((line) => `    ${line}`)
        .join('\n');
    return `// Generated by scripts/generate-runtime-bootstrap.js. Do not edit by hand.
const extensionRuntime = globalThis.chrome?.runtime || globalThis.browser?.runtime;
const getURL = extensionRuntime?.getURL;
if (typeof getURL !== 'function') {
    throw new Error('Extension runtime URL API is unavailable while loading the runtime graph');
}
export const FOUNDATION_MODULES = Object.freeze(
${moduleLiteral}
);
// Imported CONCURRENTLY. These are classic IIFE modules that all attach to one
// globalThis.YTKitCore namespace, so the browser evaluates them in completion
// order rather than list order -- which is safe only because no module calls a
// sibling at evaluation time. tests/runtime-graph-order.test.js enforces that
// property by loading the whole graph in reverse and comparing the namespace.
// (core/lifecycle-route-bridge.js used to break it: it self-installed on load
// and silently no-opped when its dependencies had not registered yet. The
// bootstrap installs it explicitly after this resolves.)
//
// This was a \`for (const m of FOUNDATION_MODULES) await import(getURL(m))\`
// loop: 75 sequential compile-and-evaluate round-trips, ~48 ms of a ~140 ms
// parse+init on the captured watch fixture. Loading concurrently lets V8
// compile the graph off-thread in parallel and costs ~18 ms for the same work.
//
// Measured alternatives that do NOT work: STATIC \`import './core/x.js'\`
// specifiers are marginally faster and spec-ordered, but resolve relative to
// the canonical extension origin, where these resources are deliberately not
// exposed under \`use_dynamic_url: true\` -- the real extension then fails to
// boot at all. Warming the fetches ahead of the sequential loop changes
// nothing, because the cost is compile, not fetch.
await Promise.all(FOUNDATION_MODULES.map((modulePath) => import(getURL(modulePath))));
`;
}

// FEATURE_SETTINGS decides which feature modules the extension loads AT ALL:
// a module whose listed keys are all explicitly false is skipped. Nothing
// validated those keys against the schema, so a renamed or mistyped key rotted
// silently, and a new gating key added to a listed module could strand the
// whole module for users who disabled only the older keys.
function assertFeatureSettingsKeysExist() {
    let schema;
    try {
        ({ SETTINGS_SCHEMA: schema } = require(path.join(ROOT, 'extension', 'core', 'settings-schema.js')));
    } catch (error) {
        throw new Error(`Could not load settings-schema.js to validate FEATURE_SETTINGS: ${error.message}`);
    }
    if (!Array.isArray(schema) || schema.length === 0) {
        throw new Error('settings-schema.js exported no SETTINGS_SCHEMA array; cannot validate FEATURE_SETTINGS');
    }
    const known = new Set(schema.map((entry) => entry.key));
    const unknown = [];
    for (const [modulePath, keys] of Object.entries(FEATURE_SETTINGS)) {
        for (const key of keys) {
            if (!known.has(key)) unknown.push(`${modulePath} -> ${key}`);
        }
    }
    if (unknown.length) {
        throw new Error(
            ['FEATURE_SETTINGS references setting keys that do not exist in SETTINGS_SCHEMA:']
                .concat(unknown.map((item) => `  ${item}`))
                .join(String.fromCharCode(10))
        );
    }
}

function main() {
    assertFeatureSettingsKeysExist();
    const modules = readRuntimeModules();
    const expected = render(modules);
    const expectedLoader = renderLoader(modules);
    const checkOnly = process.argv.includes('--check');

    if (checkOnly) {
        const actual = fs.readFileSync(OUTPUT_PATH, 'utf8');
        if (actual !== expected) {
            throw new Error('extension/runtime-bootstrap.js is stale; run npm run generate:runtime-bootstrap');
        }
        const actualLoader = fs.readFileSync(LOADER_OUTPUT_PATH, 'utf8');
        if (actualLoader !== expectedLoader) {
            throw new Error('extension/runtime-core-loader.mjs is stale; run npm run generate:runtime-bootstrap');
        }
        return;
    }

    fs.writeFileSync(OUTPUT_PATH, expected);
    fs.writeFileSync(LOADER_OUTPUT_PATH, expectedLoader);
}

try {
    main();
} catch (error) {
    console.error(error.message);
    process.exitCode = 1;
}
