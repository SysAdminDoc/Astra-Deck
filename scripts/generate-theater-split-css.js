'use strict';

// The standalone theater-split.user.js ships the same Theater Split design as
// the extension. Its stylesheet is generated from the extension's three sheets
// (extension/features/sticky-video-styles) with the standalone's own scope and
// ids, so the two can no longer drift apart one hand edit at a time.
//
// What the translation changes:
//   - html.ytkit-split-active becomes body.ts-active, and the ytkit-split
//     chrome ids and tokens become their ts- names;
//   - the accent comes from YouTube's own link color, since the standalone runs
//     without Astra Deck and has no --ytkit-accent;
//   - the extension's page and player geometry is left out. The standalone
//     reparents the player into its own overlay and keeps the structural rules
//     in STANDALONE_STRUCTURE below.
//
//   node scripts/generate-theater-split-css.js          rewrite the stylesheet
//   node scripts/generate-theater-split-css.js --check  fail if it is stale

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.join(__dirname, '..');
const STYLES_PATH = path.join(REPO_ROOT, 'extension', 'features', 'sticky-video-styles', 'index.js');
const OUTPUT_PATH = path.join(REPO_ROOT, 'theater-split.user.js');
const TEMPLATE_OPEN = 'earlyStyle.textContent = `';

// Page and player geometry the standalone owns itself, matched on selectors.
const DROPPED_SELECTORS = Object.freeze([
    /ytd-watch-flexy\s*$/, /ytd-watch-flexy #columns/, /ytd-masthead/, /#page-manager/, /ytd-app\s*$/,
    /html\.ytkit-split-active, html\.ytkit-split-active body/, /html\.ytkit-split-active body\s*$/,
    /#player-container/, /#movie_player/, /\.html5-video-container/, /video\.html5-main-video/,
    /ytd-player > #container/, /:is\(#secondary, #below, #player-full-bleed-container/,
    /:is\(#ytkit-split-wrapper, #ytkit-split-left\)/,
    /ytd-watch-flexy\.loading ytd-live-chat-frame#chat/
]);

const RENAMES = Object.freeze([
    ['--ytkit-split-accent: var(--ytkit-accent, #a78bfa);', '--ytkit-split-accent: var(--yt-spec-call-to-action, #3ea6ff);'],
    ['html:not([dark]).ytkit-split-active', 'html:not([dark]) body.ts-active'],
    ['html.ytkit-split-active', 'body.ts-active'],
    ['#ytkit-split-wrapper', '#ts-wrapper'],
    ['#ytkit-split-left', '#ts-left'],
    ['#ytkit-split-right', '#ts-right'],
    ['#ytkit-split-divider', '#ts-divider'],
    ['.ytkit-divider-pip', '.ts-divider-pip'],
    ['#ytkit-split-close', '#ts-close'],
    ['#ytkit-split-collapse-strip', '#ts-collapse-strip'],
    ['data-ytkit-panel-state', 'data-panel-state'],
    ['container: ytkit-split-owner', 'container: ts-owner'],
    ['@container ytkit-split-owner', '@container ts-owner'],
    ['--ytkit-split-', '--ts-']
]);

const STANDALONE_STRUCTURE = `
/* Generated by scripts/generate-theater-split-css.js from the extension's
   Theater Split sheets. Edit extension/features/sticky-video-styles and
   regenerate; hand edits here are overwritten. */

/* Hide masthead when overlay is active */
body.ts-active ytd-masthead,
body.ts-active #masthead-container { display: none !important; }
/* Prevent page scroll behind overlay */
body.ts-active { overflow: hidden !important; }
/* Split overlay base */
#ts-wrapper { display:none; }
body.ts-active #ts-wrapper { display:flex; }
/* Fullscreen guard: never interfere with native fullscreen */
ytd-watch-flexy[fullscreen] ~ #ts-wrapper,
body:fullscreen #ts-wrapper { display:none !important; }

/* YouTube sets view-transition-name on #secondary, #below and
   #player-full-bleed-container. That creates containing blocks which trap
   position:fixed children, so the chat and comments could not reach the
   viewport. */
body.ts-active #secondary,
body.ts-active #below,
body.ts-active #player-full-bleed-container,
body.ts-active #columns,
body.ts-active ytd-watch-flexy {
    view-transition-name: none !important;
}

/* Chat frame overrides when split is active */
body.ts-split ytd-live-chat-frame#chat,
body.ts-split ytd-live-chat-frame {
    height: 100vh !important;
    max-height: none !important;
    min-height: 0 !important;
    visibility: visible !important;
    display: flex !important;
    flex-direction: column !important;
}
body.ts-split #chat-container {
    display: block !important;
    height: auto !important;
    max-height: none !important;
    overflow: visible !important;
    visibility: visible !important;
}
body.ts-split ytd-live-chat-frame#chat > iframe,
body.ts-split ytd-live-chat-frame > iframe {
    flex: 1 !important;
    height: 100% !important;
    min-height: 0 !important;
    max-height: none !important;
}
/* Override loading visibility:hidden on chat */
body.ts-active ytd-watch-flexy.loading ytd-live-chat-frame#chat,
body.ts-active ytd-watch-flexy:not([ghost-cards-enabled]).loading #chat {
    visibility: visible !important;
}

/* The overlay's own surfaces: the page canvas, and black behind the video. */
body.ts-active #ts-wrapper { background: var(--ts-canvas) !important; color: var(--ts-text) !important; }
body.ts-active #ts-left { background: var(--ts-player) !important; }
`;

// Top-level blocks of a sheet, @-blocks kept whole.
function topLevelBlocks(css) {
    const out = [];
    let depth = 0;
    let start = 0;
    for (let i = 0; i < css.length; i += 1) {
        if (css[i] === '{') depth += 1;
        else if (css[i] === '}') {
            depth -= 1;
            if (depth === 0) {
                out.push(css.slice(start, i + 1).trim());
                start = i + 1;
            }
        }
    }
    return out.filter(Boolean);
}

function loadStyles() {
    delete require.cache[require.resolve(STYLES_PATH)];
    return require(STYLES_PATH);
}

function generateCss(styles = loadStyles()) {
    const sheets = [styles.buildSplitShellCss(), styles.buildSplitMetaCss(), styles.buildSplitCommentsCss()];
    const kept = [];
    for (const sheet of sheets) {
        for (const block of topLevelBlocks(sheet)) {
            const selector = block.slice(0, block.indexOf('{'));
            if (!block.startsWith('@') && DROPPED_SELECTORS.some((pattern) => pattern.test(selector))) continue;
            kept.push(block);
        }
    }
    let css = kept.join('\n');
    for (const [from, to] of RENAMES) css = css.split(from).join(to);
    // The standalone paints its own video surface; letterboxing stays black.
    css = css.replace('    --ts-radius: 8px;', '    --ts-player: #000000;\n    --ts-radius: 8px;');
    if (!css.includes('--ts-player: #000000;')) throw new Error('the token block lost its --ts-radius anchor');
    if (/ytkit-split-active|--ytkit-split-|#ytkit-split-|\$\{|`/.test(css)) {
        throw new Error('the translated stylesheet still names extension scope, or would break its template');
    }
    const body = `${STANDALONE_STRUCTURE}\n${css}\n`;
    return body.split('\n').map((line) => (line ? `        ${line}` : line)).join('\n') + '    ';
}

function spliceInto(source, css) {
    const start = source.indexOf(TEMPLATE_OPEN);
    if (start < 0) throw new Error(`${path.basename(OUTPUT_PATH)} has no early stylesheet template`);
    const contentStart = start + TEMPLATE_OPEN.length;
    const end = source.indexOf('`;', contentStart);
    if (end < 0) throw new Error('the early stylesheet template is not terminated');
    return source.slice(0, contentStart) + css + source.slice(end);
}

function main(args = process.argv.slice(2)) {
    const source = fs.readFileSync(OUTPUT_PATH, 'utf8');
    const expected = spliceInto(source, generateCss());
    if (args.includes('--check')) {
        if (source !== expected) {
            console.error('[generate-theater-split-css] theater-split.user.js is stale; run npm run generate:theater-split-css');
            process.exitCode = 1;
            return;
        }
        console.log('[generate-theater-split-css] OK — the standalone stylesheet matches the extension sheets');
        return;
    }
    fs.writeFileSync(OUTPUT_PATH, expected, 'utf8');
    console.log(`[generate-theater-split-css] Wrote ${path.relative(REPO_ROOT, OUTPUT_PATH)}`);
}

if (require.main === module) main();

module.exports = { generateCss, spliceInto, main, RENAMES, DROPPED_SELECTORS };
